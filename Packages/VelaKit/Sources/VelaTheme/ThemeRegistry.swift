/// Every themable color, with its default for dark and light themes.
///
/// Defaults are expressions over other tokens, so a theme that only sets a
/// handful of base colors (`window.background`, `window.foreground`,
/// `accent`) still gets a coherent result. The root values follow the
/// default themes, Palenight (dark) and Lighter (light).
public enum ThemeRegistry {
    public static let groups: [ThemeTokenGroup] = [
        .init(id: "window", title: "Window", description: "Base colors most other tokens derive from."),
        .init(id: "titleBar", title: "Title bar", description: "The toolbar area above the conversation."),
        .init(id: "sidebar", title: "Sidebar", description: "The network and channel list."),
        .init(id: "rail", title: "Rail", description: "The collapsed, icon-only sidebar."),
        .init(id: "tabs", title: "Tabs", description: "Vivaldi-style tab stacks used when navigation is set to tabs."),
        .init(id: "chat", title: "Chat", description: "The conversation view."),
        .init(id: "input", title: "Input", description: "The message composer."),
        .init(id: "memberList", title: "Member list", description: "The channel member list."),
        .init(id: "embed", title: "Embeds", description: "Link previews and inline media cards."),
        .init(id: "reactions", title: "Reactions, replies & typing", description: "IRCv3 message reactions, reply quotes and typing indicators."),
        .init(id: "controls", title: "Controls", description: "Accent, buttons, scrollbars and popovers."),
        .init(id: "status", title: "Status", description: "Semantic colors for connection state and feedback."),
        .init(id: "settings", title: "Settings window", description: "The Settings window."),
    ]

    public static let tokens: [ThemeToken] = window + titleBar + sidebar + rail + tabs + chat + input + memberList
        + embed + reactions + controls + status + settings

    public static func token(_ key: String) -> ThemeToken? {
        index[key].map { tokens[$0] }
    }

    public static func tokens(in group: String) -> [ThemeToken] {
        tokens.filter { $0.group == group }
    }

    private static let index: [String: Int] = {
        var result: [String: Int] = [:]
        for (offset, token) in tokens.enumerated() { result[token.key] = offset }
        return result
    }()

    // MARK: - Definitions

    private static func t(
        _ key: String, _ group: String, _ description: String,
        dark: TokenDefault, light: TokenDefault
    ) -> ThemeToken {
        ThemeToken(key: key, group: group, description: description, dark: dark, light: light)
    }

    private static func t(_ key: String, _ group: String, _ description: String, _ both: TokenDefault) -> ThemeToken {
        ThemeToken(key: key, group: group, description: description, dark: both, light: both)
    }

